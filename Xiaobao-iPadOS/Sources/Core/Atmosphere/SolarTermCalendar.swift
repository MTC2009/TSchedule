    static func scene(year: Int, month: Int, day: Int) -> Festival? {
        guard (firstYear..<(firstYear+days.count)).contains(year), (1...12).contains(month) else { return nil }
        let row = days[year-firstYear], i = 2*(month-1)
        for j in i...i+1 where Int(row[j]) == day {
            // Source order starts in January; the art catalog starts at Beginning of Spring.
            return Festival.solarTerms[(j+22)%24]
        }
        return nil
    }
